export const GLYPH_W = 5;
export const GLYPH_H = 7;

export const textWidth = (str, scale = 1, tracking = 1) =>
  Math.max(0, String(str).length * (GLYPH_W + tracking) * scale - tracking * scale);

export const drawText = (ctx, str, x, y, { color = '#fff', scale = 1, tracking = 1 } = {}) => {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const ty = Math.round(y);
  for (const raw of String(str)) {
    const rows = G[raw.toUpperCase()] || G['?'];
    for (let r = 0; r < 7; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < 5; c++) {
        if (bits & (1 << (4 - c))) ctx.fillRect(cx + c * scale, ty + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + tracking) * scale;
  }
};

export const drawTextCentered = (ctx, str, cx, y, opts = {}) =>
  drawText(ctx, str, cx - textWidth(str, opts.scale || 1, opts.tracking ?? 1) / 2, y, opts);
